-- ============================================================
-- BANCO DE DADOS SUPABASE - SISTEMA INTERNO MVT ADVOGADOS
-- Schema SQL completo para Reuniões, Anti No-Show e Comercial
-- ============================================================

-- 1. TABELA PRINCIPAL DE REUNIÕES & AGENDAMENTOS (ANTI NO-SHOW)
CREATE TABLE IF NOT EXISTS public.reunioes (
    id TEXT PRIMARY KEY,
    client_name TEXT NOT NULL,
    client_phone TEXT,
    lawyer TEXT DEFAULT 'Augusto',
    area TEXT DEFAULT 'Trabalhista',
    meeting_date DATE DEFAULT CURRENT_DATE,
    meeting_time TEXT NOT NULL,
    meet_link TEXT,
    status TEXT DEFAULT 'pending', -- 'pending', 'confirmed', 'noshow', 'completed'
    alert_60m_sent BOOLEAN DEFAULT false,
    alert_60m_at TIMESTAMPTZ,
    alert_30m_sent BOOLEAN DEFAULT false,
    alert_30m_at TIMESTAMPTZ,
    alert_15m_sent BOOLEAN DEFAULT false,
    alert_15m_at TIMESTAMPTZ,
    alert_0m_sent BOOLEAN DEFAULT false,
    alert_0m_at TIMESTAMPTZ,
    no_show_alert_sent BOOLEAN DEFAULT false,
    no_show_alert_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Índices de consulta rápida para o painel Anti No-Show
CREATE INDEX IF NOT EXISTS idx_reunioes_date ON public.reunioes (meeting_date);
CREATE INDEX IF NOT EXISTS idx_reunioes_status ON public.reunioes (status);
CREATE INDEX IF NOT EXISTS idx_reunioes_lawyer ON public.reunioes (lawyer);
CREATE INDEX IF NOT EXISTS idx_reunioes_area ON public.reunioes (area);

-- 2. TABELA DE HISTÓRICO DE DISPAROS E EVENTOS DA RÉGUA
CREATE TABLE IF NOT EXISTS public.historico_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_evento TEXT NOT NULL, -- 'ALERTA_60M', 'CONFIRMACAO_PRESENCA', 'NO_SHOW', 'EDICAO_CLIENTE', 'ALTERACAO_AREA'
    reuniao_id TEXT,
    client_name TEXT,
    client_phone TEXT,
    lawyer TEXT,
    meeting_time TEXT,
    descricao TEXT,
    data_evento TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_historico_data ON public.historico_eventos (data_evento DESC);
CREATE INDEX IF NOT EXISTS idx_historico_reuniao ON public.historico_eventos (reuniao_id);

-- 3. TABELA DE CLIENTES COMERCIAIS & GESTÃO DE PIPELINE (PLANILHA EXECUTIVA)
CREATE TABLE IF NOT EXISTS public.clientes_comercial (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    area TEXT DEFAULT 'Trabalhista',
    status TEXT DEFAULT 'Lead Novo',
    next_step TEXT DEFAULT 'Acompanhamento',
    notes TEXT,
    date DATE DEFAULT CURRENT_DATE,
    responsible TEXT DEFAULT 'Augusto',
    pronto_para_fechar BOOLEAN DEFAULT false,
    desqualificado BOOLEAN DEFAULT false,
    motivo_desqualificado TEXT,
    task JSONB,
    task_history JSONB DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Migração incremental segura caso a tabela já tenha sido criada:
ALTER TABLE public.clientes_comercial ADD COLUMN IF NOT EXISTS desqualificado BOOLEAN DEFAULT false;
ALTER TABLE public.clientes_comercial ADD COLUMN IF NOT EXISTS motivo_desqualificado TEXT;

CREATE INDEX IF NOT EXISTS idx_clientes_status ON public.clientes_comercial (status);
CREATE INDEX IF NOT EXISTS idx_clientes_area ON public.clientes_comercial (area);

-- 4. TABELA DE AUDITORIA & REGISTRO DE ALTERAÇÕES
CREATE TABLE IF NOT EXISTS public.historico_alteracoes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem TEXT NOT NULL, -- 'ANTI_NO_SHOW' ou 'COMERCIAL'
    registro_id TEXT,
    tipo_alteracao TEXT,
    detalhes TEXT,
    criado_em TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. HABILITAÇÃO DE ROW LEVEL SECURITY (RLS) COM POLÍTICAS DE ACESSO TOTAL
ALTER TABLE public.reunioes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historico_eventos ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.clientes_comercial ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historico_alteracoes ENABLE ROW LEVEL SECURITY;

-- Políticas de acesso livre com autenticação/chave pública da aplicação
DO $$
BEGIN
    DROP POLICY IF EXISTS "Acesso total reunioes" ON public.reunioes;
    CREATE POLICY "Acesso total reunioes" ON public.reunioes FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Acesso total historico_eventos" ON public.historico_eventos;
    CREATE POLICY "Acesso total historico_eventos" ON public.historico_eventos FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Acesso total clientes_comercial" ON public.clientes_comercial;
    CREATE POLICY "Acesso total clientes_comercial" ON public.clientes_comercial FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Acesso total historico_alteracoes" ON public.historico_alteracoes;
    CREATE POLICY "Acesso total historico_alteracoes" ON public.historico_alteracoes FOR ALL USING (true) WITH CHECK (true);
END $$;
